import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import css from '@webref/css';

const require = createRequire(import.meta.url);
const { version } = require('@webref/css/package.json');
const TARGET = new URL('../src/core/properties.data.ts', import.meta.url);
const CHROME = new URL('./data/chrome-shorthands.json', import.meta.url);
const FLOW_RELATIVE = /(^|-)(block|inline)(-|$)|-(start|end)-(start|end)-/;

/** What neither source lists: mappings two specifications give in prose, and the border widths `-webkit-border-image` sets in WebKit and Blink. */
const UNLISTED = {
  '-webkit-border-image': [
    'border-image',
    'border-top-width',
    'border-right-width',
    'border-bottom-width',
    'border-left-width',
  ],
  '-webkit-box-align': ['align-items'],
  '-webkit-box-flex': ['flex-grow'],
  '-webkit-box-ordinal-group': ['order'],
  '-webkit-box-orient': ['flex-direction'],
  '-webkit-box-pack': ['justify-content'],
  'glyph-orientation-vertical': ['text-orientation'],
};

/** The table of CSS properties the plugin ships, as source text: the specifications merged with Chrome. */
export async function generate() {
  const { properties } = await css.listAll();
  const chrome = JSON.parse(readFileSync(CHROME, 'utf8'));

  const parts = new Map();
  const aliases = {};
  const names = new Set();
  const groups = {};
  for (const property of properties) {
    names.add(property.name);
    if (property.legacyAliasOf) aliases[property.name] = property.legacyAliasOf;
    else if (property.longhands) {
      parts.set(
        property.name,
        new Set([...property.longhands, ...(property.resetLonghands ?? [])])
      );
    }
    if (property.logicalPropertyGroup) {
      (groups[property.logicalPropertyGroup] ??= []).push(property.name);
    }
  }
  for (const source of [UNLISTED, chrome.expansions]) {
    for (const [name, set] of Object.entries(source)) {
      names.add(name);
      for (const longhand of set) names.add(longhand);
      if (aliases[name]) continue;
      const known = parts.get(name) ?? new Set();
      for (const longhand of set) if (longhand !== name) known.add(longhand);
      parts.set(name, known);
    }
  }

  const byName = (a, b) => (a < b ? -1 : 1);
  const shorthands = Object.fromEntries(
    [...parts]
      .sort(([a], [b]) => byName(a, b))
      .map(([name, set]) => [name, [...set].join(' ')])
  );
  const longhands = [...names]
    .filter((name) => !parts.has(name) && !aliases[name])
    .sort(byName);
  for (const name of Object.keys(aliases).sort(byName)) {
    const target = aliases[name];
    delete aliases[name];
    aliases[name] = target;
  }

  const logicalGroups = Object.keys(groups)
    .sort()
    .map((name) => {
      const physical = groups[name].filter((member) => !FLOW_RELATIVE.test(member));
      const logical = groups[name].filter((member) => FLOW_RELATIVE.test(member));
      return `${physical.join(' ')} | ${logical.join(' ')}`;
    });

  const record = (entries) =>
    Object.entries(entries)
      .map(([name, value]) => `  ${JSON.stringify(name)}: ${JSON.stringify(value)},`)
      .join('\n');

  return `/** Generated by scripts/properties.mjs from @webref/css ${version} and ${chrome.browser}: run \`npm run properties\` to update. */

export const SHORTHANDS: Readonly<Record<string, string>> = {
${record(shorthands)}
};

export const ALIASES: Readonly<Record<string, string>> = {
${record(aliases)}
};

export const LOGICAL_GROUPS: readonly string[] = [
${logicalGroups.map((group) => `  ${JSON.stringify(group)},`).join('\n')}
];

export const LONGHANDS =
  ${JSON.stringify(longhands.join(' '))};
`;
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  const text = await generate();
  const current = (() => {
    try {
      return readFileSync(TARGET, 'utf8');
    } catch {
      return '';
    }
  })();
  if (process.argv.includes('--check')) {
    if (current !== text) {
      console.error(
        'src/core/properties.data.ts is out of date: run `npm run properties`'
      );
      process.exit(1);
    }
  } else {
    writeFileSync(TARGET, text);
    console.log(`wrote ${TARGET.pathname}`);
  }
}
